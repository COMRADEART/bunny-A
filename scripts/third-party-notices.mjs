// Writes THIRD_PARTY_NOTICES.md from the production SBOM. Rerun before each release: `node scripts/third-party-notices.mjs`.
import { writeFileSync } from "node:fs";
import assert from "node:assert/strict";
import { generateSbom } from "./bunny-sbom-provenance.mjs";

const sbom = generateSbom(".");
const unknown = sbom.components.filter((c) => !c.license || /unknown|unlicensed/i.test(c.license));
assert.equal(unknown.length, 0, `components without a licence: ${unknown.map((c) => c.name).join(", ")}`);

const byLicense = new Map();
for (const c of sbom.components) {
  const name = c.name.replace(/^.*node_modules\//, "");
  const list = byLicense.get(c.license) ?? new Set();
  list.add(`${name} ${c.version}`);
  byLicense.set(c.license, list);
}

const sections = [...byLicense.keys()].sort().map((license) =>
  `### ${license}\n\n${[...byLicense.get(license)].sort().map((p) => `- ${p}`).join("\n")}\n`);

writeFileSync("THIRD_PARTY_NOTICES.md", `# Third-party notices

Bunny A includes the open-source components below. Each npm package ships its full licence text inside its own folder
under \`node_modules/\` in the installed app. Generated by \`scripts/third-party-notices.mjs\` from the production
dependency lock (${sbom.components.length} components).

## Native components

- **Node.js runtime** — MIT, with bundled third-party licences: https://github.com/nodejs/node/blob/main/LICENSE
- **whisper.cpp / ggml** (\`whisper.dll\`, \`ggml.dll\`, \`ggml-base.dll\`) — MIT: https://github.com/ggml-org/whisper.cpp
- **.NET runtime** — MIT: https://github.com/dotnet/runtime/blob/main/LICENSE.TXT
- **cloudflared** (downloaded on request for remote access, hash-pinned) — Apache-2.0: https://github.com/cloudflare/cloudflared

## Notes on specific licences

- **MPL-2.0** (lightningcss): used unmodified. Source: https://github.com/parcel-bundler/lightningcss
- **OFL-1.1** (bundled fonts): the fonts are not sold by themselves; their licence travels with each font package.
- **CC-BY-4.0** (caniuse-lite): browser support data by caniuse.com.

## npm components by licence

${sections.join("\n")}`);
console.log(`THIRD_PARTY_NOTICES.md: ${sbom.components.length} components, ${byLicense.size} licences`);
