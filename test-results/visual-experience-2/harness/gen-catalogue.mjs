// Visual Experience 2.0: writes docs/visual-experience-2/THEME_CATALOGUE.md from the real registry (ui-theme.ts) and the
// signature comment at the top of each theme's stylesheet, so the catalogue cannot drift from the code it describes.
// Usage: node gen-catalogue.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { UI_THEME_IDS, themeManifest, FONT_PROVENANCE, FONT_STACKS, contrast, parseColor } from "../../../src/lib/bunny-host/ui-theme.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const cssDir = join(root, "src/components/island/themes");
const signature = (id) => {
  const css = readFileSync(join(cssDir, `${id === "neumorph" ? "neumorph" : id}.css`), "utf8");
  const head = css.match(/^\/\*([\s\S]*?)\*\//)?.[1] ?? "";
  const text = head.replace(/\s*\n\s*/g, " ").trim();
  const dash = text.indexOf("—");
  return dash >= 0 ? text.slice(dash + 1).trim().replace(/^signature: /, "") : "Token-driven: the engine's shared layout and materials carry this theme (see its manifest below).";
};
const shot = (rel) => (existsSync(join(root, "test-results/visual-experience-2", rel)) ? `\`test-results/visual-experience-2/${rel}\`` : `(not captured: ${rel})`);
const lines = [
  "# Theme catalogue (Visual Experience 2.0)",
  "",
  "Generated by `test-results/visual-experience-2/harness/gen-catalogue.mjs` from `src/lib/bunny-host/ui-theme.ts` and the",
  "header of each `src/components/island/themes/<id>.css`. Do not edit by hand; re-run the generator.",
  "",
  "Every theme shares one React component tree. A theme is a manifest (tokens plus structural choices) and one signature",
  "stylesheet. Contrast figures are computed from the palette by the same `contrast()` the tests use.",
  "",
  "| # | Theme | Layout | Home | Studio | Nav | Material | Variants | Notch shape |",
  "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
];
for (const id of UI_THEME_IDS) {
  const t = themeManifest(id);
  lines.push(`| ${String(t.number).padStart(2, "0")} | ${t.name} (\`${id}\`) | ${t.layout} | ${t.home} | ${t.studio} | ${t.nav} / phone ${t.phoneNav} | ${t.material} | ${t.variants.join(", ")} (default ${t.defaultVariant}) | ${t.notch.shape} |`);
}
lines.push("");
for (const id of UI_THEME_IDS) {
  const t = themeManifest(id);
  const ty = t.typography;
  const fonts = [...new Set([ty.body, ty.display, ty.mono])];
  const base = t.defaultVariant;
  lines.push(`## ${String(t.number).padStart(2, "0")} ${t.name}`, "");
  lines.push(`**Philosophy.** ${t.philosophy}`, "");
  lines.push(`**Look.** ${t.description}`, "");
  lines.push(`**Signature element.** ${signature(id)}`, "");
  lines.push("| Aspect | Definition |", "| --- | --- |");
  lines.push(`| Shell layout | \`${t.layout}\`; home composition \`${t.home}\`; Agent Studio \`${t.studio}\`; Agent frame \`${t.agentFrame}\` |`);
  lines.push(`| Navigation | desktop \`${t.nav}\`, phone \`${t.phoneNav}\` |`);
  lines.push(`| Material | \`${t.material}\`${t.blur ? `, backdrop blur ${t.blur}px` : ", no backdrop blur"} |`);
  lines.push(`| Typography | body \`${ty.body}\`, display \`${ty.display}\`, mono \`${ty.mono}\`; heading weight ${ty.headingWeight}, tracking ${ty.headingTracking}, case ${ty.headingCase}; display ×${ty.displayScale}, body ×${ty.bodyScale} |`);
  lines.push(`| Geometry | radii ${t.geometry.rSm}/${t.geometry.rMd}/${t.geometry.rLg}/${t.geometry.rShell}px, border ${t.geometry.border}px, density ${t.geometry.density} |`);
  lines.push(`| Icons | stroke ${t.icons.stroke}, ${t.icons.treatment} |`);
  lines.push(`| Motion | ${t.motion.language}: ${t.motion.description} Quick ${t.motion.quick} ms, base ${t.motion.base} ms, ease \`${t.motion.ease}\`, entrance \`${t.motion.enter}\` |`);
  lines.push(`| Notch | ${t.notch.description} Shape \`${t.notch.shape}\`, radius ${t.notch.radius}, border ${t.notch.border}, glow ${t.notch.glow ? "yes" : "no"}, font ${t.notch.font} |`);
  lines.push(`| Performance | heavy: ${t.performance.heavy.join(", ") || "none"}. Fallback: ${t.performance.fallback} |`);
  lines.push(`| Provenance | ${t.assets} Fonts: ${fonts.map((f) => `${f} (${FONT_PROVENANCE[f] ? `${FONT_PROVENANCE[f].family}, ${FONT_PROVENANCE[f].package}, ${FONT_PROVENANCE[f].license}` : "Windows system font"})`).join("; ")} |`);
  for (const variant of t.variants) {
    const p = t.palettes[variant];
    const ratio = (a, b) => contrast(parseColor(a).rgb, parseColor(b).rgb).toFixed(1);
    lines.push(`| Palette (${variant}) | page \`${p.page}\`, solid panel \`${p.panelSolid}\`, text \`${p.fg}\` (${ratio(p.fg, p.panelSolid)}:1 on the solid panel), muted \`${p.muted}\` (${ratio(p.muted, p.panelSolid)}:1), action \`${p.action}\` with ink \`${p.actionInk}\` (${ratio(p.actionInk, p.action)}:1) |`);
  }
  lines.push("");
  const alt = t.variants.find((v) => v !== base);
  lines.push(`Evidence: ${shot(`matrix/default-${base}/${id}-${base}-dashboard.png`)}, ${shot(`matrix/default-${base}/${id}-${base}-studio.png`)}, ${shot(`matrix/default-${base}/${id}-${base}-phone.png`)}${alt ? `, ${shot(`matrix/alt-${alt}/${id}-${alt}-dashboard.png`)}` : ""}, Notch ${shot(`notch/shots/${id}-top.png`)}.`, "");
}
mkdirSync(join(root, "docs/visual-experience-2"), { recursive: true });
writeFileSync(join(root, "docs/visual-experience-2/THEME_CATALOGUE.md"), lines.join("\n"));
console.log(`wrote ${UI_THEME_IDS.length} themes; fonts known: ${Object.keys(FONT_STACKS).length}`);
